"""Build a portable unit-per-file Obsidian edition from reviewed complete editions."""
from pathlib import Path
from urllib.parse import unquote, urlsplit
import hashlib,json,re,shutil,zipfile,tempfile
import pymupdf

ROOT=Path(__file__).resolve().parents[4]
BASE=Path(__file__).resolve().parent
DEST=ROOT/'out/obsidian/CEBT-II Notes'
manifest=[]
subjects=[('Equilibrium Thermodynamics','equilibrium-thermodynamics',12),('Advanced Biotechnology','advanced-biotechnology',17)]
for name,folder,expected in subjects:
    source=ROOT/'notes'/folder/'complete-obsidian.md'
    s=source.read_text()
    chunks=re.split(r'(?=^## \d{2}\. )',s,flags=re.M)[1:]
    assert len(chunks)==expected,(name,len(chunks))
    subject=DEST/name
    (subject/'figs').mkdir(parents=True,exist_ok=True)
    index=[f'# {name}\n\nRead the units in order. Equation numbers continue across this subject.\n']
    tags=[];figs=set()
    for chunk in chunks:
        first,body=chunk.rstrip().split('\n',1)
        m=re.fullmatch(r'## (\d{2})\. (.+)',first)
        number,title=m.groups()
        safe_title=re.sub(r'[<>:"/\\|?*]',' - ',title)
        safe_title=re.sub(r'\s+',' ',safe_title).strip(' .')
        filename=f'{number} - {safe_title}.md'
        content='# '+title+'\n'+re.sub(r'^(#{3,6}) ',lambda m:m[1][1:]+' ',body,flags=re.M)+'\n'
        (subject/filename).write_text(content)
        index.append(f'- [{number}. {title}](<{filename}>)')
        these=[int(n) for n in re.findall(r'\\tag\{(\d+)\}',content)]
        tags+=these
        refs=re.findall(r'!\[[^\]]*\]\(([^)]+)\)',content)
        for ref in refs:
            ref=ref.strip('<>')
            assert ref.startswith('figs/') and '..' not in ref,ref
            original=source.parent/ref;new=subject/ref
            shutil.copy2(original,new);figs.add(ref)
            assert hashlib.sha256(new.read_bytes()).digest()==hashlib.sha256(original.read_bytes()).digest()
        manifest.append({'subject':name,'path':str((subject/filename).relative_to(ROOT)),'equations':these,'figures':refs,'sha256':hashlib.sha256(content.encode()).hexdigest()})
    assert tags==list(range(1,len(tags)+1)),name
    # No scratch files, dependencies, configuration or browser-specific pages.
    for p in (subject/'figs').glob('*'):
        if 'figs/'+p.name not in figs:p.unlink()
    index.extend(['','Figures are in the adjacent `figs/` folder. Keep this folder together when copying or moving it.',''])
    if name=='Advanced Biotechnology':
        index.extend(['Gene regulation uses external supplementation to sparse course material. Synthetic condensates is the optional final unit.',''])
    (subject/(name+'.md')).write_text('\n'.join(index))

DEST.mkdir(parents=True,exist_ok=True)
(DEST/'Start here.md').write_text('# CEBT-II Notes\n\n- [Equilibrium Thermodynamics](<Equilibrium Thermodynamics/Equilibrium Thermodynamics.md>)\n- [Advanced Biotechnology](<Advanced Biotechnology/Advanced Biotechnology.md>)\n\nCopy this entire `CEBT-II Notes` folder into your existing Obsidian vault, wherever you want these subjects to sit. Each subject has numbered Markdown units and its own `figs/` folder. Keep their relative arrangement unchanged. Open a subject index and follow its unit links. Standard inline and display mathematics work without a plugin.\n')
(ROOT/'out/obsidian/README.md').write_text('# Obsidian delivery\n\n[Copy-ready folder](<CEBT-II Notes/Start here.md>)\n\nLocal ZIP: `CEBT-II-Obsidian.zip` (generated by the packaging script; the unpacked folder is tracked).\n\nCopy the entire `CEBT-II Notes` folder into your vault, or unzip the archive and copy its extracted folder. It contains 12 Thermodynamics units, 17 Biotechnology units and their figures. No importer or plugin is required. Copying individual subject folders is also fine: keep the Markdown files and `figs/` together.\n\nFor one long note per subject instead, use the `complete-obsidian.md` file and adjacent `figs/` in `notes/<subject>/`. The numbered browser pages there use GitHub-specific math formatting; the folder here is the dedicated Obsidian edition.\n\n[Review and verification record](../work/FINAL-DELIVERY.md).\n')

def validate(folder):
    links=0;images=set()
    for p in folder.rglob('*.md'):
        s=p.read_text()
        assert len(re.findall(r'^# ',s,re.M))==1,p
        assert '```math' not in s and '$`' not in s,p
        assert not re.search(r'\[\[|^>\s*\[!',s,re.M),p
        for m in re.finditer(r'(!?)\[[^\]]*\]\((?:<([^>]+)>|([^\s)]+))\)',s):
            dest=m[2] or m[3]
            if urlsplit(dest).scheme or dest.startswith('#'):continue
            target=p.parent/unquote(dest.split('#',1)[0])
            assert target.exists(),(p,dest)
            links+=1
            if m[1]:images.add(target)
    for p in images:
        pix=pymupdf.Pixmap(str(p));assert pix.width>0 and pix.height>0,p
    return {'markdown_files':len(list(folder.rglob('*.md'))),'unit_files':len(manifest),'links':links,'decoded_figures':len(images)}

results=validate(DEST)
archive=ROOT/'out/obsidian/CEBT-II-Obsidian.zip'
with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED) as z:
    for p in sorted(DEST.rglob('*')):
        if p.is_file():z.write(p,p.relative_to(DEST.parent))
with tempfile.TemporaryDirectory(prefix='cebt-obsidian-relocation-') as temp:
    relocated=Path(temp)/'My vault'/'Chemical Engineering'/'Year 3'
    relocated.mkdir(parents=True)
    with zipfile.ZipFile(archive) as z:
        assert z.testzip() is None
        z.extractall(relocated)
    assert validate(relocated/'CEBT-II Notes')==results
results['relocated_zip_links_pass']=True
results['archive_bytes']=archive.stat().st_size
results['archive_sha256']=hashlib.sha256(archive.read_bytes()).hexdigest()
(BASE/'package-manifest.json').write_text(json.dumps(manifest,indent=2,ensure_ascii=False)+'\n')
(BASE/'package-validation.json').write_text(json.dumps(results,indent=2)+'\n')
print(json.dumps(results,indent=2))
